def _num(v: Any) -> str:
    if _is_int(v):
        return str(v)
    return repr(float(v))


def _annotation(group: str, label: str, order: int, *extra: str) -> str:
    parts = [f'string UIGroup = "{group}";', f'string UIName = "{label}";', *extra, f"int UIOrder = {order};"]
    return "< " + " ".join(parts) + " >"


def _maya_declaration(p: ParameterDef, e: dict[str, Any]) -> list[str]:
    group, label, order, name = e["group"], e["label"], e["order"], e["name"]
    sem = f" : {e['semantic']}" if "semantic" in e else ""
    if p.type == "color3":
        rgb = ", ".join(_num(v) for v in p.default)
        colour = 'string UIWidget = "Color";'
        return [f"float3 {name} {_annotation(group, label, order, colour)} = {{ {rgb} }};"]
    if p.type in ("float", "int"):
        lo, hi = p.range if p.range is not None else (0.0, 1.0)
        step = "1" if p.type == "int" else "0.001"
        lo_s, hi_s = (str(int(lo)), str(int(hi))) if p.type == "int" else (_num(lo), _num(hi))
        ann = _annotation(
            group,
            label,
            order,
            'string UIWidget = "Slider";',
            f"float UIMin = {lo_s};",
            f"float UIMax = {hi_s};",
            f"float UIStep = {step};",
        )
        return [f"{p.type} {name}{sem} {ann} = {_num(p.default)};"]
    if p.type == "bool":
        return [f"bool {name} {_annotation(group, label, order)} = {'true' if p.default else 'false'};"]
    if p.type == "enum":
        fields = ":".join(p.choices)
        ann = _annotation(group, label, order, f'string UIFieldNames = "{fields}";')
        return [f"int {name} {ann} = {list(p.choices).index(p.default)};"]
    raise MaterialError(f"{p.name}: no Maya declaration for type {p.type!r}")


def _maya_components(p: ParameterDef, e: dict[str, Any]) -> list[str]:
    lines = []
    for c, default in zip(e["components"], p.default):
        ann = _annotation(e["group"], c["label"], c["order"], f'string UIFieldNames = "{e["component_choices"]}";')
        lines.append(f"int {c['name']} {ann} = {0 if default > 0 else 1};")
    return lines


def _maya_map(p: ParameterDef, m: dict[str, Any]) -> list[str]:
    space = MAYA_COLOUR_SPACES[p.colour_space or "raw"]
    return [
        f"Texture2D {m['name']}",
        "<",
        f'    string UIGroup = "Material Maps"; string UIName = "{m["label"]}"; string ResourceType = "2D";',
        (
            f'    string ResourceName = ""; int mipmaplevels = 0; int UIOrder = {m["order"]}; '
            f'string ColorSpace = "{space}";'
        ),
        ">;",
        f"bool {m['flag']}",
        "<",
        f'    string UIGroup = "Material Maps"; string UIName = "Use {m["label"]}"; int UIOrder = {m["order"] + 1};',
        "> = false;",
    ]


def maya_block(hmap: dict[str, Any], params: dict[str, ParameterDef]) -> str:
    """The text between the shell's markers: the maps, then each group in the map's group order."""
    where = hmap.get("host", "<host map>") if isinstance(hmap, dict) else "<host map>"
    findings = check_host_map(hmap, params, where)
    if findings:
        raise MaterialError("malformed host map: " + "; ".join(str(f) for f in findings))
    entries = hmap["parameters"]
    lines: list[str] = [_RULE + "material maps (generated)", ""]
    maps = sorted(((e["map"], params[n]) for n, e in entries.items() if "map" in e), key=lambda t: t[0]["order"])
    for m, p in maps:
        lines.extend(_maya_map(p, m))
    for group, _ in sorted(hmap["groups"].items(), key=lambda t: t[1]):
        rows: list[tuple[int, list[str]]] = []
        for pname, e in entries.items():
            p = params[pname]
            if p.type == "texture" or e.get("group") != group:
                continue
            if p.type == "vector3":
                rows.append((min(c["order"] for c in e["components"]), _maya_components(p, e)))
            else:
                rows.append((e["order"], _maya_declaration(p, e)))
        if not rows:
            continue
        lines.extend(["", _RULE + f"{group} (generated)", ""])
        for _, decl in sorted(rows, key=lambda t: t[0]):
            lines.extend(decl)
    return "\n".join(lines) + "\n"


def _span(text: str, begin: str, end: str, what: str) -> tuple[int, int]:
    """
    The start of the line after the ``begin`` marker and the start of the ``end`` marker line; each marker
    is a whole line (CRLF tolerated), present exactly once, in order. ``MaterialError`` otherwise.
    """
    begins = list(re.finditer(_MARKER_LINE.format(marker=re.escape(begin)), text, re.MULTILINE))
    ends = list(re.finditer(_MARKER_LINE.format(marker=re.escape(end)), text, re.MULTILINE))
    if len(begins) != 1 or len(ends) != 1:
        raise MaterialError(
            f"{what}: the markers {begin!r} and {end!r} must each appear exactly once as a line "
            f"(found {len(begins)} and {len(ends)})"
        )
    i, j = begins[0].end() + 1, ends[0].start()
    if j < i:
        raise MaterialError(f"{what}: the END marker precedes the BEGIN marker")
    return i, j


def replace_between(text: str, begin: str, end: str, body: str, what: str) -> str:
    """``text`` with the lines between the ``begin`` and ``end`` marker lines replaced by ``body``."""
    i, j = _span(text, begin, end, what)
    return text[:i] + body + text[j:]


def between(text: str, begin: str, end: str, what: str) -> str:
    """The text between the marker lines, as ``replace_between`` would replace it."""
    i, j = _span(text, begin, end, what)
    return text[i:j]


