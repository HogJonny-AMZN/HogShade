def generate(host: str, *, types: list[str] | None = None) -> str:
    """
    One host's text: ``"maya_dx11"`` the shell's material block (always the legacy union), ``"docs"`` the
    reference (``types`` restricts it). An unknown host is ``MaterialError``.
    """
    if host == "docs":
        return docs_reference(types)
    if host == "maya_dx11":
        return maya_block(host_map(host), union_of(MAYA_TYPES))
    raise MaterialError(f"no generator for host {host!r}; one of ['docs', 'maya_dx11']")


