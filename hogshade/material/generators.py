def _cell(v: Any) -> str:
    if v is None:
        return ""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_cell(x) for x in v) + "]"
    return str(v).replace("|", "\\|")


def docs_reference(type_names: list[str] | None = None) -> str:
    """The Markdown reference of the shipped types: a table per type, parameters in file order."""
    names = list(type_names) if type_names is not None else types()
    out = [
        DOCS_HEADER,
        "# Material types, the reference",
        "",
        "**Status:** Living. Generated from `hogshade/material/schema/*.material-type.json` by",
        "`tools/generate_material_ui.py --write`; edit the schema, not this file.",
        "",
    ]
    for name in names:
        mtype = type_of(name)
        out += [f"## `{name}` (version {mtype.version})", "", mtype.title + ".", ""]
        out.append("Groups: " + ", ".join(f"`{g}`" for g in mtype.groups) + ".")
        if mtype.optional_groups:
            out.append("Opt-in groups: " + ", ".join(f"`{g}`" for g in mtype.optional_groups) + ".")
        out += [
            "",
            (
                "| Parameter | Type | Default | Range | Group | Widget | Semantic | Colour space | Overridable | Tier "
                "| Doc |"
            ),
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        for p in mtype.parameters.values():
            rng = _cell(list(p.range)) + (" soft" if p.soft else "") if p.range is not None else ""
            default = _cell(p.default) if p.type != "enum" else f"`{p.default}` of {_cell(list(p.choices))}"
            out.append(
                f"| `{p.name}` | {p.type} | {default} | {rng} | {p.group} | {p.widget} | {p.semantic} | "
                f"{_cell(p.colour_space)} | {_cell(p.overridable)} | {_cell(p.tier)} | {_cell(p.doc)} |"
            )
        out.append("")
    return "\n".join(out)


