"""
HogShade: the generators: a host's material UI and the docs reference, produced from the material-type files
and a per-host map of names.
Package: hogshade/material/generators

``generate("maya_dx11")`` is the material block of ``hosts/maya_dx11/hogshade.fx`` between its two marker
lines; ``generate("docs")`` the Markdown reference of every type. The host map carries only what the schema
does not know (identifiers, labels, orders, groups); a value the schema knows is a finding in the map. The
S2 spec (Docs/superpowers/specs/s2-material-generators.md) fixes both outputs. Named ``generators``, not
``generate``: the package exports ``generate`` (failure-modes entry 13).
"""

